const GAP = 1;

export function textWidth(text, scale = 1) {
  const n = String(text).length;
  return n > 0 ? (n * 5 + (n - 1) * GAP) * scale : 0;
}

export function drawText(ctx, text, x, y, scale = 1, color = '#fff', opts = {}) {
  const { shadow = null, align = 'left', alpha = 1, spacing = GAP } = opts;
  const chars = Array.from(String(text).toUpperCase());
  const width = chars.length > 0 ? (chars.length * 5 + (chars.length - 1) * spacing) * scale : 0;
  let startX = align === 'center' ? x - width / 2 : align === 'right' ? x - width : x;
  startX = Math.round(startX);
  const startY = Math.round(y);

  const paint = (offset, fill) => {
    ctx.fillStyle = fill;
    let cx = startX + offset;
    for (const raw of chars) {
      const glyph = GLYPHS[raw] || GLYPHS[raw.toLowerCase()] || GLYPHS[' '];
      for (let row = 0; row < 7; row++) {
        const line = glyph[row];
        for (let col = 0; col < 5; col++) {
          if (line[col] === '#') {
            ctx.fillRect(cx + col * scale, startY + offset + row * scale, scale, scale);
          }
        }
      }
      cx += (5 + spacing) * scale;
    }
  };

  const previousAlpha = ctx.globalAlpha;
  ctx.globalAlpha = previousAlpha * alpha;
  if (shadow) paint(scale, shadow);
  paint(0, color);
  ctx.globalAlpha = previousAlpha;
  return width;
}
